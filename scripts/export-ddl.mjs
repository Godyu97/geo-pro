import { execFileSync } from "node:child_process";
import {
  mkdirSync,
  readFileSync,
  renameSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const target = resolve(root, "drizzle/ddl/postgresql.sql");
const args = process.argv.slice(2);

function main() {
  if (args.length > 1 || (args.length === 1 && args[0] !== "--check")) {
    throw new Error("用法：node scripts/export-ddl.mjs [--check]");
  }

  let sql;
  try {
    sql = execFileSync(
      "pnpm",
      ["exec", "drizzle-kit", "export", "--config=./drizzle.config.ts"],
      { cwd: root, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] },
    )
      .replace(/\r\n/g, "\n")
      .trim();
  } catch {
    throw new Error("DDL 导出失败；未改写快照。请检查 Drizzle 配置与 Schema。");
  }

  if (!sql.startsWith("CREATE ") || !sql.endsWith(";")) {
    throw new Error("Drizzle 未返回完整建表 SQL；未改写快照。");
  }

  const content = [
    "-- Generated by pnpm db:ddl from drizzle.config.ts. Do not edit manually.",
    "-- PostgreSQL application schema for an empty database; no data or migration history.",
    "-- Use pnpm db:migrate for managed deployments and upgrades.",
    "",
    sql,
    "",
  ].join("\n");

  if (args[0] === "--check") {
    let current;
    try {
      current = readFileSync(target, "utf8");
    } catch (error) {
      if (error.code !== "ENOENT") throw error;
    }
    if (current !== content) {
      throw new Error("全量 DDL 缺失或已过期；请运行 pnpm db:ddl 并审核差异。");
    }
    console.log("PASS: PostgreSQL 全量 DDL 与当前 Drizzle Schema 一致。");
    return;
  }

  mkdirSync(dirname(target), { recursive: true });
  const temporary = `${target}.${process.pid}.tmp`;
  try {
    writeFileSync(temporary, content, { flag: "wx" });
    renameSync(temporary, target);
  } finally {
    rmSync(temporary, { force: true });
  }
  console.log("已更新 drizzle/ddl/postgresql.sql；请审核并运行 pnpm db:ddl:check。");
}

try {
  main();
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
